// Tipos derivados de la migración real ejecutada en PostgreSQL aislado.
// Después de aplicar en Supabase, sustituir con la generación oficial del proyecto.
import { PGlite } from '@electric-sql/pglite';
import { readFile, readdir, writeFile } from 'node:fs/promises';
const db = new PGlite();
try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;`);
  for (const file of (await readdir('supabase/migrations')).filter(f => f.endsWith('.sql')).sort()) {
    await db.exec(await readFile(`supabase/migrations/${file}`, 'utf8'));
  }
  const columns = (await db.query(`select table_name,column_name,udt_name,is_nullable,column_default from information_schema.columns where table_schema = 'public' order by table_name,ordinal_position`)).rows;
  const functions = (await db.query(`select p.proname,p.proargnames,p.proargtypes::oid[] as argtypes,p.pronargdefaults,p.proretset,t.typname as return_type from pg_proc p join pg_namespace n on n.oid=p.pronamespace join pg_type t on t.oid=p.prorettype where n.nspname='public' order by p.proname`)).rows;
  const typeNames = new Map((await db.query('select oid,typname from pg_type')).rows.map(t => [t.oid,t.typname]));
  const scalar = type => ['int2','int4','int8','numeric','float4','float8'].includes(type) ? 'number' : type === 'bool' ? 'boolean' : ['json','jsonb'].includes(type) ? 'Json' : 'string';
  let code = '// Generated by npm run db:types:local from the tested migration. Remote schema comparison pending.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = { public: { Tables: {\n';
  for (const table of new Set(columns.map(c => c.table_name))) {
    const fields = columns.filter(c => c.table_name === table);
    code += `  ${table}: {\n`;
    for (const kind of ['Row','Insert','Update']) {
      code += `    ${kind}: {\n`;
      for (const c of fields) {
        const optional = kind === 'Update' || kind === 'Insert' && (c.is_nullable === 'YES' || c.column_default !== null);
        code += `      ${c.column_name}${optional ? '?' : ''}: ${scalar(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''};\n`;
      }
      code += '    };\n';
    }
    code += '    Relationships: [];\n  };\n';
  }
  code += '}; Views: { [key in never]: never }; Enums: { [key in never]: never }; CompositeTypes: { [key in never]: never }; Functions: {\n';
  for (const fn of functions) {
    const args = (fn.proargnames ?? []).map((name,i) => `${name}${i >= fn.argtypes.length - fn.pronargdefaults ? '?' : ''}: ${scalar(typeNames.get(fn.argtypes[i]))}`).join('; ');
    const result = fn.proretset ? `Database['public']['Tables']['${fn.return_type}']['Row'][]` : scalar(fn.return_type);
    code += `  ${fn.proname}: { Args: { ${args} }; Returns: ${result} };\n`;
  }
  code += '} } };\n';
  await writeFile('src/lib/supabase/database.types.ts', code);
  console.log(`Generated ${new Set(columns.map(c => c.table_name)).size} tables and ${functions.length} functions.`);
} finally { await db.close(); }
